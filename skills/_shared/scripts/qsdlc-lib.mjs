export function splitFrontmatter(text) {
  if (!text) return { front: null, body: text ?? '' };
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!m) return { front: null, body: text };
  return { front: m[1], body: m[2] };
}

function stripComment(line) {
  let q = null;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (q) {
      if (c === q) q = null;
    } else if (c === '"' || c === "'") {
      q = c;
    } else if (c === '#' && (i === 0 || /\s/.test(line[i - 1]))) {
      return line.slice(0, i);
    }
  }
  return line;
}

function splitInline(s) {
  const out = [];
  let cur = '';
  let q = null;
  for (const c of s) {
    if (q) {
      cur += c;
      if (c === q) q = null;
    } else if (c === '"' || c === "'") {
      q = c;
      cur += c;
    } else if (c === ',') {
      out.push(cur);
      cur = '';
    } else cur += c;
  }
  if (cur.trim() !== '') out.push(cur);
  return out;
}

export function parseScalar(raw) {
  const s = raw.trim();
  if (s.startsWith('[') && s.endsWith(']')) return splitInline(s.slice(1, -1)).map(parseScalar);
  if ((s.startsWith('"') && s.endsWith('"') && s.length >= 2) || (s.startsWith("'") && s.endsWith("'") && s.length >= 2)) {
    return s.slice(1, -1);
  }
  if (s === 'true') return true;
  if (s === 'false') return false;
  if (/^-?\d+(\.\d+)?$/.test(s)) return Number(s);
  return s;
}

export function parseYamlLite(text) {
  const lines = [];
  for (const raw of String(text ?? '').split(/\r?\n/)) {
    const t = stripComment(raw);
    if (!t.trim()) continue;
    lines.push({ indent: t.match(/^ */)[0].length, text: t.trim() });
  }
  let i = 0;
  const isItem = (l) => l.text === '-' || l.text.startsWith('- ');

  function parseBlock() {
    if (i >= lines.length) return null;
    return isItem(lines[i]) ? parseList(lines[i].indent) : parseMap(lines[i].indent);
  }

  function parseMap(indent) {
    const obj = {};
    while (i < lines.length && lines[i].indent === indent && !isItem(lines[i])) {
      const m = lines[i].text.match(/^([^:]+?):(?:\s+(.*))?$/);
      i++;
      if (!m) continue;
      const key = m[1].trim().replace(/^["']|["']$/g, '');
      const rest = m[2];
      if (rest === undefined || rest === '') {
        if (i < lines.length && lines[i].indent > indent) obj[key] = parseBlock();
        else if (i < lines.length && lines[i].indent === indent && isItem(lines[i])) obj[key] = parseList(indent);
        else obj[key] = '';
      } else {
        obj[key] = parseScalar(rest);
      }
    }
    return obj;
  }

  function parseList(indent) {
    const arr = [];
    while (i < lines.length && lines[i].indent === indent && isItem(lines[i])) {
      const content = lines[i].text.slice(1).trim();
      if (content === '') {
        i++;
        arr.push(i < lines.length && lines[i].indent > indent ? parseBlock() : '');
        continue;
      }
      const looksMap = /^[^:\s"'[{][^:]*?:(\s+.*)?$/.test(content);
      if (looksMap) {
        const offset = lines[i].text.length - content.length;
        lines[i] = { indent: indent + offset, text: content };
        arr.push(parseMap(indent + offset));
      } else {
        arr.push(parseScalar(content));
        i++;
      }
    }
    return arr;
  }

  const result = parseBlock();
  return result ?? {};
}

export function parsePolicy(root) {
  const text = readText(path.join(root, '.qsdlc', 'factory', 'policy.md'));
  if (text === null) return null;
  const { front } = splitFrontmatter(text);
  if (front === null) return {};
  return parseYamlLite(front);
}

export function globToRegExp(glob) {
  const g = toPosix(glob);
  let re = '';
  for (let i = 0; i < g.length; i++) {
    const c = g[i];
    if (c === '*') {
      if (g[i + 1] === '*') {
        if (g[i + 2] === '/') {
          re += '(?:.*/)?';
          i += 2;
        } else {
          re += '.*';
          i += 1;
        }
      } else re += '[^/]*';
    } else if (c === '?') re += '[^/]';
    else if ('\\^$+.()|{}[]'.includes(c)) re += '\\' + c;
    else re += c;
  }
  return new RegExp('^' + re + '$', process.platform === 'win32' ? 'i' : '');
}

export function matchesAny(globs, file) {
  const f = toPosix(file).replace(/^\.\//, '');
  return (globs || []).some((g) => globToRegExp(String(g)).test(f));
}

export function sanitizeCell(value) {
  let s = String(value ?? '').replace(/[\t\r\n]+/g, ' ').trim();
  if (/^[=+\-@]/.test(s)) s = "'" + s;
  return s;
}

export function parseTsv(text) {
  const lines = String(text ?? '').split(/\r?\n/);
  while (lines.length && lines[lines.length - 1] === '') lines.pop();
  return lines.map((l) => l.split('\t'));
}

export function tsvLine(cells) {
  return cells.map(sanitizeCell).join('\t') + '\n';
}

export const PII_PATTERNS = [
  { name: 'ssn', re: /\b\d{3}-\d{2}-\d{4}\b/ },
  { name: 'dob', re: /\b(?:dob|date of birth|birth ?date)\b[^\n]{0,24}\d{1,2}[/-]\d{1,2}[/-]\d{2,4}/i },
  {
    name: 'address',
    re: /\b\d{1,5}\s+(?:[A-Z][a-z]+\s+){1,3}(?:Street|St|Avenue|Ave|Road|Rd|Drive|Dr|Lane|Ln|Court|Ct|Boulevard|Blvd|Way)\b/,
  },
];

export function findPii(text) {
  const hits = [];
  const lines = String(text ?? '').split(/\r?\n/);
  lines.forEach((line, idx) => {
    for (const p of PII_PATTERNS) {
      if (p.re.test(line)) hits.push({ line: idx + 1, kind: p.name });
    }
  });
  return hits;
}

export function parseCorrections(text) {
  const rows = parseTsv(text);
  if (!rows.length) return [];
  return rows.slice(1).map((cells) => {
    const o = {};
    CORR_HEADER.forEach((h, i) => {
      o[h] = cells[i] ?? '';
    });
    o._cells = cells.length;
    return o;
  });
}

export function groupByClass(rows) {
  const map = new Map();
  for (const r of rows) {
    if (!map.has(r.class)) map.set(r.class, []);
    map.get(r.class).push(r);
  }
  return map;
}

export function latestPerClass(rows) {
  const out = new Map();
  for (const [cls, list] of groupByClass(rows)) out.set(cls, list[list.length - 1]);
  return out;
}

export function generateRules(rows) {
  const enforced = [...latestPerClass(rows).values()]
    .filter((r) => r.status === 'enforced')
    .sort((a, b) => a.class.localeCompare(b.class));
  const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');
  const lines = [
    RULES_BANNER,
    '# Rules',
    '',
    '| rule | enforced by | level | proof | expires |',
    '|---|---|---|---|---|',
    ...enforced.map((r) => `| ${esc(r.class)} | ${esc(r.enforcer)} | ${esc(r.level)} | ${esc(r.proof)} | ${esc(r.expires)} |`),
    '',
  ];
  return lines.join('\n');
}

export function computeMetrics(rows, { days = 30, now = new Date() } = {}) {
  const groups = groupByClass(rows);
  const cutoff = now.getTime() - days * 86400000;
  let enforcedNow = 0;
  let docNow = 0;
  let everEnforced = 0;
  const uncovered = [];
  const tte = [];
  for (const [cls, list] of groups) {
    const latest = list[list.length - 1];
    const occ = list.filter((r) => r.status === 'open' || r.status === 'repeat');
    if (latest.status === 'enforced') {
      enforcedNow++;
      if (latest.level === 'doc') docNow++;
    }
    const firstEnforced = list.find((r) => r.status === 'enforced');
    if (firstEnforced) {
      everEnforced++;
      const second = occ[1];
      if (second) {
        const d = (Date.parse(firstEnforced.ts) - Date.parse(second.ts)) / 86400000;
        if (Number.isFinite(d) && d >= 0) tte.push(d);
      }
    }
    if ((latest.status === 'open' || latest.status === 'repeat') && occ.length >= 2) uncovered.push(cls);
  }
  const repeats = rows.filter((r) => r.status === 'repeat' && Date.parse(r.ts) >= cutoff).length;
  tte.sort((a, b) => a - b);
  const median = tte.length ? tte[Math.floor((tte.length - 1) / 2)] : null;
  return {
    window_days: days,
    classes: groups.size,
    enforced_classes: enforcedNow,
    doc_level_share: enforcedNow ? Number((docNow / enforcedNow).toFixed(4)) : 0,
    repeat_rate: everEnforced ? Number((repeats / everEnforced).toFixed(4)) : 0,
    time_to_enforce_days: median,
    uncovered_classes: uncovered.sort(),
  };
}

export function parseArgs(argv) {
  const flags = {};
  const positional = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith('--')) {
      const eq = a.indexOf('=');
      if (eq > 0) flags[a.slice(2, eq)] = a.slice(eq + 1);
      else if (i + 1 < argv.length && !argv[i + 1].startsWith('--')) flags[a.slice(2)] = argv[++i];
      else flags[a.slice(2)] = true;
    } else positional.push(a);
  }
  return { flags, positional };
}
