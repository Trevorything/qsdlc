#!/usr/bin/env node
// matrix_md.mjs — generate references/matrix.md from assets/matrix/*.json so the human-readable
// matrix can never drift from the cards the roll actually deals.
//   node matrix_md.mjs            write ../references/matrix.md
//   node matrix_md.mjs --check    exit 1 if the file on disk differs from what would be generated
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { loadMatrix, KINDS } from './roll.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', 'references', 'matrix.md');
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');
const list = (a) => (a && a.length ? a.join(', ') : 'none');

export function renderMatrix() {
  const m = loadMatrix();
  const L = [];
  L.push('# The matrix', '', '<!-- GENERATED by scripts/matrix_md.mjs from assets/matrix/*.json. Edit the json, then re-run. -->', '');
  L.push('Cards describe **structure only**: layout, grammar, motion, finish. Colour, type, radius and borders come from `brand-bind.json`, never from a card.', '');
  L.push('`roll.mjs` deals one archetype, the BI cards, the motion cards, two finish cards and one signature moment, filtered by `fits`, `needs`, cost budget and rhythm rules.', '');
  L.push('## Narrative spine (fixed by kind, not rolled)', '', '| Kind | Spine |', '|---|---|');
  for (const [k, v] of Object.entries(KINDS)) L.push(`| \`${k}\` | ${v.narrative} |`);
  L.push('');
  const decks = [
    ['Deck A. Layout archetypes', m.archetype, ['id', 'name', 'fits', 'cost', 'reduced', 'phone']],
    ['Deck B. BI grammar (FT Visual Vocabulary relationship first, then the form)', m.bi, ['id', 'relationship', 'kitChart', 'fits', 'a11y', 'cost']],
    ['Deck C. Motion devices', m.motion, ['id', 'shows', 'impl', 'fits', 'cost', 'reduced']],
    ['Finish cards (pick 2)', m.finish, ['id', 'name', 'fits', 'reduced']],
    ['Signature moments (pick 1, 2 on long pages)', m.signature, ['id', 'name', 'fits', 'needs', 'reduced']]
  ];
  for (const [title, cards, cols] of decks) {
    L.push(`## ${title}`, '', `| ${cols.join(' | ')} |`, `|${cols.map(() => '---').join('|')}|`);
    for (const c of cards) L.push(`| ${cols.map((k) => esc(Array.isArray(c[k]) ? list(c[k]) : c[k])).join(' | ')} |`);
    L.push('');
  }
  L.push('## Banned motion', '');
  const banned = JSON.parse(fs.readFileSync(path.join(HERE, '..', 'assets', 'matrix', 'motion.json'), 'utf8')).banned || [];
  banned.forEach((b) => L.push(`- ${b}`));
  L.push('', `Total cards: ${Object.values(m).reduce((n, d) => n + d.length, 0)}`, '');
  return L.join('\n');
}

const USAGE = `usage: node matrix_md.mjs [--check]
  (no flag)  regenerate references/matrix.md from assets/matrix/*.json
  --check    exit 1 if references/matrix.md is out of sync; never writes
  -h, --help print this help and exit 0 (writes nothing)`;

function main() {
  const args = process.argv.slice(2);
  if (args.includes('-h') || args.includes('--help')) { console.log(USAGE); return; }
  const unknown = args.filter((a) => a !== '--check');
  if (unknown.length) { console.error(`matrix_md: unknown argument ${unknown.map((a) => `"${a}"`).join(', ')}\n${USAGE}`); process.exit(2); }
  const text = renderMatrix();
  if (args.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== text) { console.error('matrix.md is out of sync with assets/matrix/*.json; run: node scripts/matrix_md.mjs'); process.exit(1); }
    console.log('matrix.md in sync'); return;
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true }); fs.writeFileSync(OUT, text); console.log(`wrote ${OUT}`);
}
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) main();
